const filePath = 'src/data/products.ts';
let content = fs.readFileSync(filePath, 'utf8');

// Regex matches from id down to productUrl or lore
const regex = /("id":\s*"(\d+)",[\s\S]*?)(?=\n\s*\})/g;

let modified = content.replace(regex, (match, body, id) => {
  // If it's already got culturalTags, skip? No, wait, some might not have it or we overwrite it.
  // Actually, wait, the regex matches up to the ending bracket.
  // Let's just do a simpler search and replace if culturalTags isn't present, or replace it.
  if (culturalTagsData[id]) {
    const specificTags = JSON.stringify(culturalTagsData[id]);
    if (match.includes('"culturalTags":')) {
      // Replace existing culturalTags
      return match.replace(/"culturalTags":\s*\[.*?\]/s, `"culturalTags": ${specificTags}`);
    } else {
      // Append culturalTags
      return match + `,\n    "culturalTags": ${specificTags}`;
    }
  }
  return match;
});

fs.writeFileSync(filePath, modified, 'utf8');
